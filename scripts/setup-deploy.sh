zone="$(pulumi env get "$PULUMI_ORG/$ESC_ENV" 'pulumiConfig["sema:route53ZoneId"]' --value string 2>/dev/null || true)"
[[ -n "$zone" ]] || { warn "$PULUMI_ORG/$ESC_ENV has no sema:route53ZoneId, which fences the role's DNS access."; exit 1; }
(cd infra/bootstrap && { pulumi stack select "$BOOTSTRAP_STACK" 2>/dev/null || pulumi stack init "$BOOTSTRAP_STACK"; })
if [[ "$(cat infra/bootstrap/Pulumi.prod.yaml)" != "$(printf 'environment:\n  - %s' "$ESC_ENV")" ]]; then
  warn "Pulumi rewrote infra/bootstrap/Pulumi.prod.yaml; put back just the import (environment: - $ESC_ENV)."
  exit 1
fi
if (cd infra/bootstrap && pulumi preview --stack "$BOOTSTRAP_STACK" --expect-no-changes >/dev/null 2>&1); then
  note "$BOOTSTRAP_STACK is already up to date."
else
  step "Pulumi previews 3 IAM resources the first time: the boundary policy, the role and its"
  step "inline policy, and no OIDC provider. Check them, then choose 'yes'."
  (cd infra/bootstrap && pulumi up --stack "$BOOTSTRAP_STACK")
fi
write_env AWS_DEPLOY_ROLE_ARN "$(cd infra/bootstrap && pulumi stack output deployRoleArn --stack "$BOOTSTRAP_STACK")"
step "Stash's bootstrap stack should still show no changes, since the provider was only read:"
note "  in the Stash checkout, cd infra/bootstrap && pulumi preview --stack $PULUMI_ORG/stash-bootstrap/prod"
pause

# ── 8 ─────────────────────────────────────────────────────────────────────
stage "Prod stack: move the Lambda roles under /sema/"
say "CI's role can only manage roles under /sema/ that carry the boundary, so this one move is"
say "yours. 'make deploy' runs 'pulumi up' on $PROD_STACK, then invalidates CloudFront."
# all_moved "n/total" succeeds when every one of a non-zero number of roles has moved.
all_moved() { [[ "${1#*/}" != 0 && "${1%/*}" == "${1#*/}" ]]; }
# bounded_roles prints how many of the stack's IAM roles sit under /sema/ with the boundary, of all.
bounded_roles() {
  (cd infra && pulumi stack export --stack "$PROD_STACK") | jq -r '
    [.deployment.resources[] | select(.type == "aws:iam/role:Role") | .outputs] |
    "\(map(select(.path == "/sema/" and ((.permissionsBoundary // "") | endswith(":policy/sema-lambda-boundary")))) | length)/\(length)"'
}
note "Checking whether that already happened (the preview builds the Lambdas and the web app)."
moved="$(bounded_roles)"
if all_moved "$moved" && (cd infra && pulumi preview --stack "$PROD_STACK" --expect-no-changes >/dev/null 2>&1); then
  note "Already done: $moved roles are under /sema/ with the boundary, and prod matches this checkout."
else
  say "Expect the 7 Lambda roles and their policies to be replaced (create before delete) and every"
  say "Lambda updated; this also deploys any code on master that prod doesn't run yet. Each function"
  say "errors for a few seconds while its role switches, and SQS retries absorb that."
  warn "Nothing protected (the table, the content bucket, the vector bucket) should show as"
  warn "replaced or deleted."
  make deploy PULUMI_ORG="$PULUMI_ORG"
  moved="$(bounded_roles)"
  all_moved "$moved" || { warn "Only $moved roles are under /sema/ with the boundary: check the update above."; exit 1; }
  printf '  %s✓ %s roles%s are under /sema/ with the boundary\n' "$GREEN" "$moved" "$RESET"
  say "Previewing again: it should now show no changes."
  (cd infra && pulumi preview --stack "$PROD_STACK" --expect-no-changes) ||
    { warn "The preview still shows changes: CI's role may not be able to make them."; exit 1; }
fi
url="$(cd infra && pulumi stack output url --stack "$PROD_STACK")"
open_url "$url"
step "Sign in and check that items load: every Lambda now runs as its new role."
pause

finish
}

run_wizard "$@"; exit
