# cloud_resources prints how many resources the Cloud stack holds (0 if it doesn't exist).
cloud_resources() {
  local count
  count="$( (cd infra && pulumi stack export --stack "$PROD_STACK" 2>/dev/null) |
    jq '.deployment.resources // [] | length' 2>/dev/null || true)"
  printf '%s\n' "${count:-0}"
}
# config_keys prints, as a JSON array, the config keys the old stack file sets.
config_keys() {
  grep -oE '^  [A-Za-z0-9_-]+:[A-Za-z0-9_-]+:' "$LOCAL_STACK_CONFIG" | sed -E 's/^  //; s/:$//' |
    jq -R -s 'split("\n") | map(select(length > 0))'
}
# unlock asks for the passphrase and reads the old stack's config, secrets shown, into $WORK.
unlocked=0
unlock() {
  (( unlocked )) && return 0
  LOCAL_STACK_CONFIG="${LOCAL_STACK_CONFIG:-$(_existing LOCAL_STACK_CONFIG || true)}"
  [[ -n "$LOCAL_STACK_CONFIG" ]] || { warn "Set LOCAL_STACK_CONFIG in $ENV_FILE to the old stack file."; exit 1; }
  mkdir -p "$WORK/project"
  cp infra/Pulumi.yaml "$WORK/project/Pulumi.yaml"
  cp "$LOCAL_STACK_CONFIG" "$WORK/project/Pulumi.prod.yaml"
  if [[ -z "${PULUMI_CONFIG_PASSPHRASE:-}" ]]; then
    printf '  %sPassphrase of the local prod stack:%s ' "$BOLD" "$RESET"
    read -rs PULUMI_CONFIG_PASSPHRASE || { printf '\n'; warn "No passphrase given."; exit 1; }
    printf '\n'
  fi
  if ! local_pulumi config --stack prod --json --show-secrets > "$WORK/local-config.json"; then
    warn "Couldn't read the local stack's config: check the passphrase and $LOCAL_STACK_CONFIG."
    exit 1
  fi
  unlocked=1
}

