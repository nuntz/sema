# local_pulumi runs pulumi against the old local stack from a scratch project holding
# infra/Pulumi.yaml and the old stack config, for commands that don't run the program.
local_pulumi() {
  PULUMI_BACKEND_URL="$LOCAL_BACKEND" PULUMI_CONFIG_PASSPHRASE="$PULUMI_CONFIG_PASSPHRASE" \
    pulumi --cwd "$WORK/project" "$@"
}
# local_program runs the program in infra/ against the old local stack and its old config.
local_program() {
  (cd infra && PULUMI_BACKEND_URL="$LOCAL_BACKEND" PULUMI_CONFIG_PASSPHRASE="$PULUMI_CONFIG_PASSPHRASE" \
    pulumi "$@" --stack prod --config-file "$LOCAL_STACK_CONFIG")
